import { build } from 'esbuild';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const version = JSON.parse(await readFile(resolve(root, 'node_modules/monaco-editor/package.json'), 'utf8')).version;
if (version !== '0.53.0') throw new Error(`Expected Monaco 0.53.0, got ${version}`);
const license = await readFile(resolve(root, 'node_modules/monaco-editor/LICENSE'), 'utf8');
const notice = '/* Monaco Editor ' + version + '\n' + license.replaceAll('*/', '* /') + '\n*/';
const worker = await build({ absWorkingDir: root, entryPoints: ['node_modules/monaco-editor/esm/vs/editor/editor.worker.js'], bundle: true, format: 'iife', write: false, minify: true, target: 'es2022' });
await mkdir(resolve(root, 'media'), { recursive: true });
await build({ absWorkingDir: root, entryPoints: ['src/sourceExport/viewer.ts'], outfile: 'media/sourceViewer.js', bundle: true, format: 'iife', minify: true, target: 'es2022', loader: { '.ttf': 'dataurl' }, define: { __SNL_EDITOR_WORKER__: JSON.stringify(worker.outputFiles[0].text) }, legalComments: 'inline', banner: { js: notice } });
console.log('Built offline Monaco 0.53.0 classic IIFE, CSS + embedded codicon font and blob worker');
